import 'dart:convert';
import 'dart:io';

import 'comun.dart';

// Todo lo que se distribuye dentro de la app debe ser compatible con Apache-2.0
// y abierto: nada GPL/AGPL/LGPL ni componentes propietarios. Este guardián
// clasifica la licencia de cada paquete del pubspec.lock y, con `--escribir`,
// regenera THIRD-PARTY-NOTICES.md; sin él, comprueba que esté al día.
const Map<String, String> _firmas = <String, String>{
  'GNU AFFERO GENERAL PUBLIC': 'AGPL',
  'GNU LESSER GENERAL PUBLIC': 'LGPL',
  'GNU GENERAL PUBLIC': 'GPL',
  'Server Side Public License': 'SSPL',
  'Mozilla Public License': 'MPL-2.0',
  'Apache License': 'Apache-2.0',
  'Permission is hereby granted, free of charge': 'MIT',
  'Redistribution and use in source and binary forms': 'BSD',
  'Permission to use, copy, modify, and/or distribute': 'ISC',
  'zlib License': 'Zlib',
};

/// Paquetes que solo se compilan para Linux o Windows: el APK y el IPA no los
/// llevan, así que su licencia no entra en lo que se distribuye. `dbus` es MPL
/// y lo trae la implementación de Linux del selector de archivos.
const Set<String> _soloEscritorio = <String>{
  'dbus',
  'file_picker_linux',
  'windows_file_picker',
  'flutter_secure_storage_linux',
  'flutter_secure_storage_windows',
  'path_provider_linux',
  'path_provider_windows',
};

/// Licencias SPDX de crates de Rust que se aceptan. Una expresión con `OR` vale
/// si alguna de sus opciones vale; con `AND`, si todas valen.
const Set<String> _spdxPermitidas = <String>{
  'Apache-2.0',
  'MIT',
  'BSD-2-Clause',
  'BSD-3-Clause',
  'ISC',
  'Zlib',
  'Unicode-3.0',
  'Unicode-DFS-2016',
  'CC0-1.0',
  'Apache-2.0 WITH LLVM-exception',
  'BSL-1.0',
  '0BSD',
};

bool _spdxValida(String expresion) => expresion
    .replaceAll('(', '')
    .replaceAll(')', '')
    .split(RegExp(r'\s+OR\s+|/'))
    .any(
      (String opcion) => opcion
          .split(RegExp(r'\s+AND\s+'))
          .every((String l) => _spdxPermitidas.contains(l.trim())),
    );

const Set<String> _permitidas = <String>{
  'Apache-2.0',
  'MIT',
  'BSD',
  'ISC',
  'Zlib',
};

String _cachePub() {
  final String? env = Platform.environment['PUB_CACHE'];
  if (env != null && env.isNotEmpty) {
    return env;
  }
  final String home =
      Platform.environment['HOME'] ??
      Platform.environment['LOCALAPPDATA'] ??
      '';
  return Platform.isWindows ? '$home\\Pub\\Cache' : '$home/.pub-cache';
}

void main(List<String> args) {
  final Informe inf = Informe('licencias');
  final List<String> lock = File('pubspec.lock').readAsLinesSync();
  final List<(String, String, String, String)> paquetes =
      <(String, String, String, String)>[];
  String? nombre;
  String? fuente;
  String? version;
  String? dependencia;
  void volcar() {
    if (nombre != null && fuente == 'hosted' && version != null) {
      paquetes.add((nombre, version, dependencia ?? '', ''));
    }
  }

  for (final String l in lock) {
    final RegExpMatch? p = RegExp(r'^  ([a-z0-9_]+):$').firstMatch(l);
    if (p != null) {
      volcar();
      nombre = p.group(1);
      fuente = null;
      version = null;
      dependencia = null;
      continue;
    }
    final RegExpMatch? s = RegExp(r'^    source: (\w+)').firstMatch(l);
    if (s != null) fuente = s.group(1);
    final RegExpMatch? v = RegExp(r'^    version: "([^"]+)"').firstMatch(l);
    if (v != null) version = v.group(1);
    final RegExpMatch? d = RegExp(
      r'^    dependency: "?([^"]+)"?',
    ).firstMatch(l);
    if (d != null) dependencia = d.group(1);
  }
  volcar();

  final StringBuffer avisos = StringBuffer()
    ..writeln('# Third-party notices')
    ..writeln()
    ..writeln(
      'NB Books Mobile includes the following third-party packages. Each one keeps its own licence;',
    )
    ..writeln(
      'the full text of every licence follows its entry. This file is generated by',
    )
    ..writeln(
      '`dart run tool/guardianes/licencias.dart --escribir` from `pubspec.lock`.',
    )
    ..writeln()
    ..writeln(
      'Fonts bundled in `assets/fonts/` (Manrope and Space Grotesk) are licensed under the',
    )
    ..writeln(
      'SIL Open Font License 1.1. Flutter and its SDK packages are licensed under the BSD 3-Clause',
    )
    ..writeln(
      'licence. Native libraries brought in by these packages (AndroidX, CameraX, zxing-cpp, SQLite)',
    )
    ..writeln('are covered by the licences listed with each package.')
    ..writeln();
  final String raiz = '${_cachePub()}/hosted/pub.dev';
  for (final (String n, String ver, String dep, String _) in paquetes) {
    if (dep == 'direct dev' || _soloEscritorio.contains(n)) {
      continue; // herramientas de desarrollo o solo de escritorio: no viajan
    }
    final Directory dir = Directory('$raiz/$n-$ver');
    if (!dir.existsSync()) {
      inf.fallo(
        'pubspec.lock',
        '$n $ver no está en la caché de pub (ejecuta flutter pub get)',
      );
      continue;
    }
    final List<File> lic = dir
        .listSync()
        .whereType<File>()
        .where(
          (File f) => RegExp(
            r'^(LICEN[CS]E|COPYING)',
            caseSensitive: false,
          ).hasMatch(f.uri.pathSegments.last),
        )
        .toList();
    // El orden de listSync depende del sistema de archivos: se ordena para que
    // el aviso generado sea el mismo en cualquier máquina.
    lic.sort((File a, File b) => a.path.compareTo(b.path));
    if (lic.isEmpty) {
      inf.fallo(n, 'sin archivo de licencia');
      continue;
    }
    final String texto = lic.first.readAsStringSync();
    String tipo = 'desconocida';
    for (final MapEntry<String, String> e in _firmas.entries) {
      if (texto.toLowerCase().contains(e.key.toLowerCase())) {
        tipo = e.value;
        break;
      }
    }
    if (!_permitidas.contains(tipo)) {
      inf.fallo(n, 'licencia no admitida: $tipo');
    }
    avisos
      ..writeln('## $n $ver ($tipo)')
      ..writeln()
      ..writeln('```text')
      ..writeln(texto.trim())
      ..writeln('```')
      ..writeln();
  }
  // El motor de lectura: los crates de Rust que se enlazan en
  // `libnb_books_motor.so`, con la licencia que declara cada uno.
  final ProcessResult meta = Process.runSync('cargo', <String>[
    'metadata',
    '--manifest-path',
    'native/Cargo.toml',
    '--format-version',
    '1',
    '--locked',
    '--filter-platform',
    'aarch64-linux-android',
  ]);
  if (meta.exitCode != 0) {
    inf.fallo('native/Cargo.lock', 'cargo metadata falló: ${meta.stderr}');
  } else {
    final List<String> crates = <String>[];
    final Map<String, dynamic> datos =
        jsonDecode(meta.stdout as String) as Map<String, dynamic>;
    for (final dynamic c in datos['packages'] as List<dynamic>) {
      final Map<String, dynamic> m = c as Map<String, dynamic>;
      final String n = m['name'] as String;
      final String v = m['version'] as String;
      if (n == 'nb_books_motor' || n == 'nb-books-lector') {
        continue; // los propios del proyecto
      }
      String? l = m['license'] as String?;
      final String? archivo = m['license_file'] as String?;
      if (l == null && archivo != null) {
        // Sin expresión SPDX: se lee el texto de la licencia que declara.
        final String texto = File(
          '${File(m['manifest_path'] as String).parent.path}/$archivo',
        ).readAsStringSync().toLowerCase();
        for (final MapEntry<String, String> e in _firmas.entries) {
          if (texto.contains(e.key.toLowerCase())) {
            l = e.value == 'BSD' ? 'BSD-3-Clause' : e.value;
            break;
          }
        }
      }
      if (l == null || !_spdxValida(l)) {
        inf.fallo('native/Cargo.lock', '$n $v: licencia no admitida: $l');
      }
      crates.add('| `$n` | $v | $l |');
    }
    crates.sort();
    avisos
      ..writeln('## Rust crates linked into the reading engine')
      ..writeln()
      ..writeln(
        'The reading engine (`libnb_books_motor.so`) is the NB Books reader crate, Apache-2.0,',
      )
      ..writeln(
        'plus these crates. Their licence texts are published with each crate on crates.io.',
      )
      ..writeln()
      ..writeln('| Crate | Version | Licence |')
      ..writeln('|---|---|---|')
      ..writeAll(crates, '\n')
      ..writeln()
      ..writeln()
      ..writeln('## PDFium (chromium/7881)')
      ..writeln()
      ..writeln(
        '`libpdfium.so` is the PDFium build from bblanchon/pdfium-binaries, without the JavaScript',
      )
      ..writeln(
        'engine. PDFium is licensed under the BSD 3-Clause and Apache-2.0 licences; its notice ships',
      )
      ..writeln('in the APK alongside the library.')
      ..writeln();
  }
  final File destino = File('THIRD-PARTY-NOTICES.md');
  final String nuevo = avisos.toString();
  if (args.contains('--escribir')) {
    destino.writeAsStringSync(nuevo);
  } else if (!destino.existsSync() || destino.readAsStringSync() != nuevo) {
    final List<String> viejo = destino.existsSync()
        ? destino.readAsLinesSync()
        : <String>[];
    final List<String> lineas = nuevo.split('\n');
    for (int i = 0; i < lineas.length; i++) {
      if (i >= viejo.length || viejo[i] != lineas[i]) {
        stderr.writeln('primera diferencia en la línea ${i + 1}: ${lineas[i]}');
        break;
      }
    }
    inf.fallo(
      'THIRD-PARTY-NOTICES.md',
      'desactualizado (dart run tool/guardianes/licencias.dart --escribir)',
    );
  }
  exit(inf.cerrar());
}
